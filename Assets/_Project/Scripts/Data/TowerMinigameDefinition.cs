using System.Collections.Generic;
using UnityEngine;

namespace MathGame.Data
{
    [CreateAssetMenu(menuName = "MathGame/Minigames/Tower Minigame", fileName = "TowerMinigame_")]
    public class TowerMinigameDefinition : MinigameDefinition
    {
        // Одно число в списке = одна башня внутри мини-игры, значение —
        // сколько големов в этой башне. По умолчанию 2 -> 3 -> 4, как в
        // задании, но можно добавить/убрать/изменить прямо в инспекторе,
        // без единой строчки кода.
        public List<int> towerSizes = new List<int> { 2, 3, 4 };

        public int heroStartingPower = 5;

        // Насколько сила героя растёт за КАЖДУЮ победу — фиксированное
        // число, не "ответ этого примера" (раньше было именно так: сила
        // прибавляла ответ голема, из-за чего число скакало непредсказуемо
        // и вдобавок могло ронять силу героя вниз между башнями, когда
        // включался потолок — игрок явно попросил сделать рост
        // предсказуемым и только в одну сторону, вверх). Было 2, снижено до
        // 1: чем быстрее растёт сила героя, тем быстрее она упирается в
        // потолок диапазона чисел (см. EffectivePowerCap в
        // TowerMinigameController) — а как только герой застревает РОВНО на
        // потолке, вообще ВСЕ примеры следующей башни разом становятся
        // "сразу верными" (герою уже некуда расти, значит и "пока не
        // верных" построить нельзя). Медленный рост даёт больше этажей
        // пройти, прежде чем упереться в потолок — см. также расширенный
        // минимальный диапазон чисел в SettingsPanel.MinNumberRangeWidth.
        public int powerPerWin = 1;

        // 0 = без ограничения. Если сила героя не должна расти бесконечно,
        // здесь задаётся потолок — но он только ОСТАНАВЛИВАЕТ рост
        // (сила героя никогда не опустится ниже уже достигнутой), не
        // отнимает уже набранное.
        public int powerCap = 0;

        // Сколько големов в только что появившейся башне заведомо
        // "проходные" (их сила ≤ силы героя) — остальные заведомо сильнее
        // героя на этот момент. Без этого ограничения при большом запасе
        // силы героя относительно диапазона чисел все големы в башне могут
        // оказаться проходными одновременно, и выбор перестаёт быть
        // выбором. По умолчанию 1 (не 2) — по просьбе игрока, для
        // упрощения: один сразу понятный правильный вариант на этаже,
        // а не "выбирай из двух". Заодно это структурно исключает саму
        // возможность двух одинаковых "лёгких" примеров на одном этаже:
        // при значении 2 оба слота заполнялись из одного диапазона
        // [0, сила героя] и МОГЛИ совпасть (редко, но наблюдалось); при
        // значении 1 заполнять из этого диапазона просто нечего дважды.
        public int maxBeatableAtOnce = 1;
    }
}
